//! Emit the static site: UI assets + snapshot + queries + the vendored
//! relate-wasm module, ready for any static host (Cloudflare Pages).

use std::io::Read;
use std::path::Path;

use sha2::{Digest, Sha256};

use crate::error::{ToolError, ToolResult};

/// The pinned relate-wasm release vendored into dist/ (SCA posture: site
/// visitors must never trust a CDN for the engine). sha256 of the tarball.
const WASM_PACKAGE: &str = "@relate/relate-wasm";
const WASM_VERSION: &str = "1.0.1";
const WASM_TARBALL_SHA256: &str =
    "8bf25d16cb3b28eefa3e4cf7f6ee367af218ec35ad4e7ff89791dc5ee8766f12";

fn wasm_tarball_url() -> String {
    // scoped tarball filenames drop the @scope: @relate/relate-wasm → relate-wasm-<v>.tgz
    let name = WASM_PACKAGE.split('/').next_back().unwrap_or(WASM_PACKAGE);
    format!("https://registry.npmjs.org/{WASM_PACKAGE}/-/{name}-{WASM_VERSION}.tgz")
}

/// Write `queries.js`: every Cypher constant the browser backend needs,
/// serialized from the Rust constants — sync with the engine by construction.
fn queries_js() -> ToolResult<String> {
    use crate::graph::queries as q;
    use crate::graph::write as w;
    let map = serde_json::json!({
        // reads
        "LIVE_PACKAGES": q::LIVE_PACKAGES,
        "LIVE_DEPENDS_ON": q::LIVE_DEPENDS_ON,
        "HISTORY": q::HISTORY,
        "USAGE": q::USAGE,
        "COMMITS": q::COMMITS,
        "META": q::META,
        "META_COUNTS": q::META_COUNTS,
        "META_TOTAL": q::META_TOTAL,
        "META_DETAILED": q::META_DETAILED,
        "SHA_DATE": q::SHA_DATE,
        // replay (snapshot → in-browser graph)
        "MERGE_PACKAGES": w::MERGE_PACKAGES,
        "MERGE_PACKAGE_DETAILED": w::MERGE_PACKAGE_DETAILED,
        "MERGE_COMMITS": w::MERGE_COMMITS,
        "MERGE_PEOPLE": w::MERGE_PEOPLE,
        "MERGE_PROJECT": w::MERGE_PROJECT,
        "MERGE_HAS_MANIFEST": w::MERGE_HAS_MANIFEST,
        "MERGE_ROOT": w::MERGE_ROOT,
        "MERGE_DECLARES": w::MERGE_DECLARES,
        "MERGE_DEPENDS_ON": w::MERGE_DEPENDS_ON,
        "MERGE_IMPORTS": w::MERGE_IMPORTS,
        "MERGE_ADDED": w::MERGE_ADDED,
        "MERGE_REMOVED": w::MERGE_REMOVED,
        "MERGE_TOUCHED": w::MERGE_TOUCHED,
    });
    Ok(format!(
        "// generated by bomvoyage {} — Cypher the static backend runs; do not edit\nwindow.BOMVOYAGE_QUERIES = {};",
        env!("CARGO_PKG_VERSION"),
        serde_json::to_string_pretty(&map)?
    ))
}

/// The static index: the embedded one with the backend scripts injected
/// BEFORE app.js (the backend must exist before init() runs). Asset URLs
/// in the source index are already relative — subpath-safe by construction.
fn index_html() -> ToolResult<String> {
    let inject = r#"<script src="queries.js"></script>
<script src="wasm-backend.js"></script>
<script src="cytoscape.min.js"></script>"#;
    let html =
        crate::server::INDEX_HTML.replace("<script src=\"cytoscape.min.js\"></script>", inject);
    if !html.contains("wasm-backend.js") {
        return Err(ToolError::Other(
            "index.html transform failed: could not inject the static backend".into(),
        ));
    }
    Ok(html)
}

/// Download + verify + unpack the pinned relate-wasm release into
/// `dist/relate/` (relate.js, relate_bg.wasm, snippets/, … — everything
/// the ES-module glue imports at runtime).
fn bundle_wasm(out: &Path) -> ToolResult<()> {
    use flate2::read::GzDecoder;

    let agent = ureq::AgentBuilder::new()
        .timeout(std::time::Duration::from_secs(60))
        .build();
    let url = wasm_tarball_url();
    let response = agent
        .get(&url)
        .set(
            "User-Agent",
            concat!("bomvoyage/", env!("CARGO_PKG_VERSION")),
        )
        .call()
        .map_err(|e| ToolError::Other(format!("relate-wasm download failed ({url}): {e}")))?;
    let mut tarball = Vec::new();
    response
        .into_reader()
        .read_to_end(&mut tarball)
        .map_err(|e| ToolError::Other(format!("relate-wasm download truncated: {e}")))?;
    let actual = Sha256::digest(&tarball)
        .iter()
        .map(|b| format!("{b:02x}"))
        .collect::<String>();
    if actual != WASM_TARBALL_SHA256 {
        return Err(ToolError::Other(format!(
            "relate-wasm tarball checksum mismatch: expected {WASM_TARBALL_SHA256}, got {actual} — not shipping it"
        )));
    }

    let relate_dir = out.join("relate");
    std::fs::create_dir_all(&relate_dir)?;
    let gz = GzDecoder::new(std::io::Cursor::new(&tarball));
    let mut archive = tar::Archive::new(gz);
    let mut wrote = 0;
    for entry in archive
        .entries()
        .map_err(|e| ToolError::Other(format!("relate-wasm tarball unreadable: {e}")))?
    {
        let mut entry =
            entry.map_err(|e| ToolError::Other(format!("relate-wasm tarball unreadable: {e}")))?;
        let path = entry
            .path()
            .map_err(|e| ToolError::Other(format!("relate-wasm tarball unreadable: {e}")))?
            .to_path_buf();
        // entries live under package/; strip it; ship everything runtime-
        // relevant, skip .d.ts/README (not imported by the browser)
        let Some(rel) = path.strip_prefix("package/").ok().map(|p| p.to_path_buf()) else {
            continue;
        };
        if rel.extension().map(|e| e == "d.ts").unwrap_or(false)
            || rel.file_name() == Some(std::ffi::OsStr::new("README.md"))
        {
            continue;
        }
        let dest = relate_dir.join(&rel);
        if let Some(parent) = dest.parent() {
            std::fs::create_dir_all(parent)?;
        }
        entry.unpack(&dest).map_err(|e| {
            ToolError::Other(format!(
                "relate-wasm unpack failed ({}): {e}",
                rel.display()
            ))
        })?;
        wrote += 1;
    }
    if wrote == 0 {
        return Err(ToolError::Other("relate-wasm tarball had no files".into()));
    }
    Ok(())
}

/// Write the whole dist tree. Returns the file list for the summary print.
pub fn emit(out: &Path, snapshot: &crate::site::dump::Snapshot) -> ToolResult<Vec<(String, u64)>> {
    std::fs::create_dir_all(out)?;
    let mut written: Vec<(String, u64)> = Vec::new();

    let mut put = |rel: &str, bytes: &[u8]| -> ToolResult<()> {
        let dest = out.join(rel);
        if let Some(parent) = dest.parent() {
            std::fs::create_dir_all(parent)?;
        }
        std::fs::write(&dest, bytes)?;
        written.push((rel.to_string(), bytes.len() as u64));
        Ok(())
    };

    put("index.html", index_html()?.as_bytes())?;
    let snapshot_json = serde_json::to_vec_pretty(snapshot)?;
    put("snapshot.json", &snapshot_json)?;
    put("queries.js", queries_js()?.as_bytes())?;
    put("app.js", crate::server::APP_JS.as_bytes())?;
    put("search.js", crate::server::SEARCH_JS.as_bytes())?;
    put("style.css", crate::server::STYLE_CSS.as_bytes())?;
    put("cytoscape.min.js", crate::server::CYTOSCAPE_JS)?;
    put("wasm-backend.js", crate::server::WASM_BACKEND_JS.as_bytes())?;

    bundle_wasm(out)?;
    for rel in ["relate/relate.js", "relate/relate_bg.wasm"] {
        let meta = std::fs::metadata(out.join(rel))?;
        written.push((rel.to_string(), meta.len()));
    }

    Ok(written)
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn index_transform_injects_backend_and_stays_relative() {
        let html = index_html().unwrap();
        assert!(html.contains("<script src=\"queries.js\"></script>"));
        assert!(html.contains("<script src=\"wasm-backend.js\"></script>"));
        // backend must load BEFORE app.js (init() runs at app.js load)
        assert!(
            html.find("wasm-backend.js").unwrap() < html.find("app.js").unwrap(),
            "wasm-backend.js must load before app.js"
        );
        assert!(!html.contains("src=\"/"), "no root-absolute asset refs");
        assert!(!html.contains("href=\"/"), "no root-absolute asset refs");
    }

    #[test]
    fn queries_js_covers_every_constant_the_backend_needs() {
        let js = queries_js().unwrap();
        for key in [
            "LIVE_PACKAGES",
            "LIVE_DEPENDS_ON",
            "HISTORY",
            "USAGE",
            "COMMITS",
            "META",
            "META_COUNTS",
            "META_TOTAL",
            "META_DETAILED",
            "SHA_DATE",
            "MERGE_PACKAGES",
            "MERGE_COMMITS",
            "MERGE_PEOPLE",
            "MERGE_PROJECT",
            "MERGE_HAS_MANIFEST",
            "MERGE_ROOT",
            "MERGE_DECLARES",
            "MERGE_DEPENDS_ON",
            "MERGE_IMPORTS",
            "MERGE_ADDED",
            "MERGE_REMOVED",
            "MERGE_TOUCHED",
        ] {
            assert!(
                js.contains(&format!("\"{key}\"")),
                "queries.js missing {key}"
            );
        }
        // must parse as JSON (strip the JS statement terminator)
        let parsed: serde_json::Value =
            serde_json::from_str(js.split_once(" = ").unwrap().1.trim().trim_end_matches(';'))
                .unwrap_or(serde_json::Value::Null);
        assert!(!parsed.is_null(), "queries.js payload is valid JSON");
    }
}
